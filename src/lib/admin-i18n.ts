export const adminDictionaries: Record<AdminLang, AdminDict> = { fr, en };

export async function getAdminLang(): Promise<AdminLang> {
  const v = (await cookies()).get("admin_lang")?.value;
  return v === "en" ? "en" : "fr";
}

export async function getAdminDict() {
  const lang = await getAdminLang();
  return { lang, t: adminDictionaries[lang] };
}
